# ----- kleisli_list.py -----------------------------------------------------

kleisli = lambda g, f: (lambda x: mu(fmap(g, f(x))))
f = lambda x: [x, x + 1]
g = lambda x: [x * 2]
h = lambda x: [x, -x]

assert all(kleisli(kleisli(h, g), f)(x) == kleisli(h, kleisli(g, f))(x)
           for x in range(-5, 6))
assert all(kleisli(f, eta)(x) == f(x) == kleisli(eta, f)(x)
           for x in range(-5, 6))
print("laws pass;  ((h .K g) .K f)(2) =", kleisli(kleisli(h, g), f)(2))


