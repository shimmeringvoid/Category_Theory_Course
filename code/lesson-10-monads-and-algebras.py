# ----- monad_laws.py — List and Maybe, laws by enumeration -----------------

from itertools import product as cartesian

eta  = lambda x: [x]
mu   = lambda xss: [x for xs in xss for x in xs]     # Lesson 3's flatten
fmap = lambda f, xs: [f(x) for x in xs]

def lists_over(base, maxlen=2):
    out = [[]]
    for k in range(1, maxlen + 1):
        out += [list(t) for t in cartesian(base, repeat=k)]
    return out

T1 = lists_over([0, 1]); T2 = lists_over(T1); T3 = lists_over(T2)

assert all(mu(mu(x)) == mu(fmap(mu, x)) for x in T3)          # associativity
assert all(mu(eta(x)) == x == mu(fmap(eta, x)) for x in T1)   # unit laws
print(f"List : associativity on {len(T3)} T\u00b3 values, units on {len(T1)} — pass")

J     = lambda x: ('Just', x)                        # Maybe's eta
fmapM = lambda f, m: None if m is None else J(f(m[1]))
muM   = lambda mm: None if mm is None else mm[1]     # collapse one layer

M1 = [None] + [J(x) for x in (0, 1)]
M2 = [None] + [J(m) for m in M1]
M3 = [None] + [J(m) for m in M2]

assert all(muM(muM(m)) == muM(fmapM(muM, m)) for m in M3)
assert all(muM(J(m)) == m == muM(fmapM(J, m)) for m in M1)
print(f"Maybe: associativity on {len(M3)} T\u00b3 values, units on {len(M1)} — pass")

# ----- powerset_monad.py — unions of unions --------------------------------

from itertools import combinations

def powerset(xs):
    xs = list(xs)
    return [frozenset(c) for r in range(len(xs) + 1)
            for c in combinations(xs, r)]

etaP  = lambda x: frozenset([x])                        # singleton
muP   = lambda ss: frozenset(x for s in ss for x in s)  # union
fmapP = lambda f, s: frozenset(f(x) for x in s)         # direct image

P1 = powerset([0, 1]); P2 = powerset(P1); P3 = powerset(P2)
assert all(muP(muP(a)) == muP(fmapP(muP, a)) for a in P3)
assert all(muP(etaP(s)) == s == muP(fmapP(etaP, s)) for s in P1)
print(f"Powerset: associativity on {len(P3)} values,",
      f"units on {len(P1)} — pass")

# ----- kleisli_rel.py — relations are Kleisli arrows -----------------------

def kleisli(g, f):
    "g after f, for the power set monad"
    return lambda a: muP(fmapP(g, f(a)))

def compose_rel(S, R):
    "S after R, for relations given as sets of pairs"
    return {(a, c) for (a, b) in R for (b2, c) in S if b == b2}

R = {(1, 'a'), (1, 'b'), (2, 'c')}
S = {('a', 'x'), ('b', 'y'), ('c', 'y')}
f = lambda a: frozenset(b for (a2, b) in R if a2 == a)
g = lambda b: frozenset(c for (b2, c) in S if b2 == b)

graph = {(a, c) for a in (1, 2) for c in kleisli(g, f)(a)}
print("Kleisli composite   :", sorted(graph))
print("relational composite:", sorted(compose_rel(S, R)))

# ----- evaluators.py — the sum is an algebra, the average is not -----------

from fractions import Fraction

avg = lambda xs: Fraction(sum(xs), len(xs))       # an exact average
T2 = [xss for xss in lists_over(lists_over([0, 1]))
      if xss and all(xss)]            # non-empty lists of non-empty lists
ok_sum = all(sum(mu(xss)) == sum(fmap(sum, xss)) for xss in T2)
bad    = [xss for xss in T2 if avg(mu(xss)) != avg(fmap(avg, xss))]
print("sum satisfies the algebra law on all", len(T2), "values:", ok_sum)
print("the average fails it on", len(bad), "of them; first:", bad[0])


