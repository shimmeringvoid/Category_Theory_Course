# ----- free.py — foldMap is the transpose ----------------------------------

def fold_map(f, unit, op):
    "the unique monoid hom  List X -> M  extending  f : X -> M"
    def hat(xs):
        acc = unit
        for x in xs:
            acc = op(acc, f(x))
        return acc
    return hat

f   = {'a': 2, 'b': 3}.get
hat = fold_map(f, 0, lambda m, n: m + n)      # target monoid (Z, +, 0)

import itertools
samples = [list(t) for k in range(4)
                   for t in itertools.product('ab', repeat=k)]
assert hat([]) == 0                            # unit to unit
assert all(hat(xs + ys) == hat(xs) + hat(ys)   # concat to +
           for xs in samples for ys in samples)
assert all(hat([x]) == f(x) for x in 'ab')     # hat . eta == f
print("fold_map is a monoid hom; hat.eta == f;",
      "hat(['a','b','a']) =", hat(['a','b','a']))

# ----- setup.py — the category class and two orders ------------------------

from itertools import product

class FiniteCategory:
    """objects, arrows (name -> (dom, cod)), a composition table,
       and a chosen identity arrow for each object."""
    def __init__(self, objects, arrows, comp, ident):
        self.obj, self.ar = set(objects), arrows
        self.comp, self.id = comp, ident

    def dom(self, a): return self.ar[a][0]
    def cod(self, a): return self.ar[a][1]
    def composable(self, g, f): return self.dom(g) == self.cod(f)

    def check(self):
        # 1. each identity is typed X -> X
        for X in self.obj:
            assert self.ar[self.id[X]] == (X, X)
        # 2. every composable pair has a composite, correctly typed
        for g, f in product(self.ar, repeat=2):
            if self.composable(g, f):
                gf = self.comp[(g, f)]
                assert self.ar[gf] == (self.dom(f), self.cod(g))
        # 3. identity law on both sides
        for f in self.ar:
            X, Y = self.ar[f]
            assert self.comp[(self.id[Y], f)] == f
            assert self.comp[(f, self.id[X])] == f
        # 4. associativity
        for h, g, f in product(self.ar, repeat=3):
            if self.composable(h, g) and self.composable(g, f):
                assert self.comp[(h, self.comp[(g, f)])] == \
                       self.comp[(self.comp[(h, g)], f)]
        return True

def arrows_between(C, X, Y):
    "all arrows X -> Y of the finite category C"
    return [a for a, (d, c) in C.ar.items() if d == X and c == Y]

def make_poset(objs, leq):
    "a finite preorder as a thin category; the arrow a -> b is named 'a<=b'"
    ar = {f"{a}<={b}": (a, b) for a in objs for b in objs if leq(a, b)}
    comp = {(g, f): f"{ar[f][0]}<={ar[g][1]}"
            for g in ar for f in ar if ar[f][1] == ar[g][0]}
    return FiniteCategory(objs, ar, comp, {a: f"{a}<={a}" for a in objs})

from itertools import product as cartesian

# two small orders, as thin categories
Div   = make_poset({1, 2, 3, 6}, lambda a, b: b % a == 0)  # divisibility
Chain = make_poset({0, 1, 2},    lambda a, b: a <= b)      # 0 <= 1 <= 2

# ----- adjoint_finder.py — search for a partner ----------------------------

def monotone_maps(C, D):
    "all monotone maps C -> D between finite posets"
    Cobjs = sorted(C.obj, key=str)
    for values in cartesian(sorted(D.obj, key=str), repeat=len(Cobjs)):
        g = dict(zip(Cobjs, values))
        if all(not arrows_between(C, x, y) or arrows_between(D, g[x], g[y])
               for x in C.obj for y in C.obj):
            yield g

def find_right_adjoints(f, C, D):
    "all monotone g : D -> C  with   f(x) <= y   iff   x <= g(y)"
    return [g for g in monotone_maps(D, C)
            if all(bool(arrows_between(D, f[x], y)) ==
                   bool(arrows_between(C, x, g[y]))
                   for x in C.obj for y in D.obj)]

f = {0: 1, 1: 2, 2: 6}              # Chain {0,1,2}  ->  Div {1,2,3,6}
print("right adjoints of f    :", find_right_adjoints(f, Chain, Div))

f_bad = {1: 1, 2: 1, 3: 1, 6: 1}    # Div -> Chain, constant at 1
print("right adjoints of f_bad:", find_right_adjoints(f_bad, Div, Chain))


