# ----- orbits.py — equivariant maps, both ways -----------------------------

from itertools import product as cartesian

Z3, S = range(3), range(6)
act = lambda s, g: (s + 2 * g) % 6          # the action of Z/3 on S

into_S = [a for a in cartesian(S, repeat=3)             # a[f] = alpha(f)
          if all(a[(f + g) % 3] == act(a[f], g)
                 for f in Z3 for g in Z3)]
out_of_S = [b for b in cartesian(Z3, repeat=6)          # b[s] = beta(s)
            if all(b[act(s, g)] == (b[s] + g) % 3
                   for s in S for g in Z3)]
print("y* => S :", len(into_S), "of", 6 ** 3)
print("S => y* :", len(out_of_S), "of", 3 ** 6)
