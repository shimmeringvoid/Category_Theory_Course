# ----- yoneda_poset.py — an element is its down-set ------------------------

objs = {1, 2, 3, 6}
downset = {a: {x for x in objs if a % x == 0} for a in objs}

for a in objs:
    for b in objs:
        assert (b % a == 0) == (downset[a] <= downset[b])  # a|b iff ds(a) ⊆ ds(b)

for a in sorted(objs):
    print(f"downset({a}) = {sorted(downset[a])}")

# ----- yoneda_count.py — Nat(y∗, y∗) has exactly |Hom| elements ------------

from itertools import product as cartesian

H = [0, 1, 2]
comp = lambda a, b: (a + b) % 3            # a . b  in Z3

nats = []
for vals in cartesian(H, repeat=3):
    alpha = dict(zip(H, vals))
    if all(alpha[comp(f, g)] == comp(alpha[f], g)   # naturality
           for f in H for g in H):
        nats.append(alpha)

print(f"natural transformations y* => y* : {len(nats)}")
for a in nats:
    assert all(a[f] == comp(a[0], f) for f in H)    # = postcompose by a[0]
    print(f"  {a}  =  postcompose by {a[0]}")

# ----- presheaves.py — presheaves on a finite category, and maps between them ---

from itertools import product as cartesian

# the category  V ==s,t==> E ;  ar[name] = (source, target)
objs = ['V', 'E']
ar   = {'iV': ('V', 'V'), 'iE': ('E', 'E'),
        's':  ('V', 'E'), 't':  ('V', 'E')}
comp = {('iV', 'iV'): 'iV', ('iE', 'iE'): 'iE', ('s', 'iV'): 's',
        ('t', 'iV'): 't', ('iE', 's'): 's', ('iE', 't'): 't'}

def hom(X, A):
    "the arrows X -> A"
    return [h for h, (d, c) in ar.items() if d == X and c == A]

class Presheaf:
    "sets[X] is F(X);  act[g] is F(g) : F(Y) -> F(X)  for  g : X -> Y"
    def __init__(self, sets, act):
        self.sets, self.act = sets, act

def y(A):
    "the representable presheaf: arrows into A, acting by precomposition"
    sets = {X: hom(X, A) for X in objs}
    act  = {g: {h: comp[(h, g)] for h in sets[c]}
            for g, (d, c) in ar.items()}
    return Presheaf(sets, act)

def nat(F, G):
    "all natural transformations F => G, by exhaustive search"
    def functions(X):
        dom, cod = F.sets[X], G.sets[X]
        return [dict(zip(dom, vals))
                for vals in cartesian(cod, repeat=len(dom))]
    out = []
    for fam in cartesian(*[functions(X) for X in objs]):
        alpha = dict(zip(objs, fam))
        if all(alpha[d][F.act[g][e]] == G.act[g][alpha[c][e]]
               for g, (d, c) in ar.items() for e in F.sets[c]):
            out.append(alpha)
    return out

print("yV:", y('V').sets, "  yE:", y('E').sets)

