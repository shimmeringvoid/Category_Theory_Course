#!/usr/bin/env python3
"""Regenerate code/*.py and notebooks/*.ipynb from the lesson pages.

The lesson pages are the single source of truth for the course's Python.
Every code box on a page (they all sit inside the optional labs and the
optional parts of exercises) is copied, in page order, into

    code/lesson-NN-<slug>.py          a plain script
    notebooks/lesson-NN-<slug>.ipynb  a Jupyter notebook, one cell per box

Usage, from the repository root:

    python3 tools/sync_code.py            # rewrite the generated files
    python3 tools/sync_code.py --check    # exit 1 if any of them is stale

Only the standard library is needed.
"""
import glob, html, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

CODE_BOX = re.compile(
    r'<div class="code"[^>]*>\s*<div class="code-bar"><span class="fname">'
    r'<b>(?P<name>.*?)</b>(?P<desc>.*?)</span>.*?</div>\s*'
    r'<pre><code>(?P<code>.*?)</code></pre>'
    r'(?:\s*<div class="out"><span class="lbl">output</span>(?P<out>.*?)</div>)?'
    r'\s*</div>', re.S)


def text(fragment):
    "HTML fragment -> plain text"
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", fragment))).strip()


def lesson_pages(root=ROOT):
    return sorted(glob.glob(os.path.join(root, "lesson-[0-9][0-9]-*.html")))


class Lesson:
    "One lesson page and the code boxes on it."

    def __init__(self, path):
        self.path = path
        self.stem = os.path.splitext(os.path.basename(path))[0]
        self.number = int(self.stem.split("-")[1])
        self.html = open(path, encoding="utf-8").read()
        m = re.search(r"<title>(.*?) — Intro to Category Theory", self.html, re.S)
        self.title = html.unescape(m.group(1)).strip()
        lede = re.search(r'<p class="lede">(.*?)</p>', self.html, re.S)
        self.lede = text(lede.group(1)) if lede else ""
        self.blocks = [self._block(m) for m in CODE_BOX.finditer(self.html)]

    def _block(self, m):
        before = self.html[:m.start()]
        sections = re.findall(r'<div class="sec-no">(.*?)</div>', before, re.S)
        where = text(sections[-1]) if sections else ""
        last_section = before.rfind('<div class="sec-no">')
        exercises = re.findall(r'<span class="pn">(Exercise \d+)</span>',
                               before[last_section:])
        if exercises:
            where = exercises[-1]
        out = m.group("out")
        return {
            "name": text(m.group("name")),
            "desc": text(m.group("desc")).lstrip("—- ").strip(),
            "code": html.unescape(m.group("code")).strip("\n"),
            "output": None if out is None else html.unescape(out).rstrip("\n"),
            "where": where,
        }

    # ---- the generated script ------------------------------------------
    def script(self):
        lines = [
            f'"""Lesson {self.number:02d} · {self.title} — the optional Python labs.',
            "",
            f"Every code box of {self.stem}.html, in page order.",
            "Python is optional in this course: the lesson is complete without it.",
            "",
            "Generated by tools/sync_code.py — edit the lesson page, not this file.",
            f"Run with:  python3 code/{self.stem}.py",
            '"""',
        ]
        where = None
        for b in self.blocks:
            if b["where"] != where:
                where = b["where"]
                lines += ["", "", "# " + "=" * 74, f"# {where}", "# " + "=" * 74]
            label = b["name"] + (f" — {b['desc']}" if b["desc"] else "")
            lines += ["", f"# ----- {label} " + "-" * max(3, 68 - len(label)), ""]
            lines += b["code"].split("\n")
        return "\n".join(lines) + "\n"

    # ---- the generated notebook ----------------------------------------
    def notebook(self):
        cells, count = [], 0

        def md(source):
            cells.append({"cell_type": "markdown", "id": f"m{len(cells):03d}",
                          "metadata": {}, "source": source.splitlines(True)})

        def code(source, output):
            nonlocal count
            count += 1
            outputs = [] if output is None else [{
                "name": "stdout", "output_type": "stream",
                "text": (output + "\n").splitlines(True)}]
            cells.append({"cell_type": "code", "execution_count": count,
                          "id": f"c{len(cells):03d}", "metadata": {},
                          "outputs": outputs, "source": source.splitlines(True)})

        md(f"# Lesson {self.number:02d} · {self.title}\n\n{self.lede}\n\n"
           f"This notebook collects every Python block from the optional labs "
           f"and exercises of [the lesson page](../{self.stem}.html), in page "
           f"order. Run the cells from top to bottom; later cells use names "
           f"defined in earlier ones.\n\n"
           f"Python is optional in this course — the lesson is complete without "
           f"it. *Generated by `tools/sync_code.py`: edit the lesson page, not "
           f"this file.*")
        where = None
        for b in self.blocks:
            if b["where"] != where:
                where = b["where"]
                md(f"## {where}")
            md(f"**`{b['name']}`**" + (f" — {b['desc']}" if b["desc"] else ""))
            code(b["code"], b["output"])
        nb = {"cells": cells,
              "metadata": {
                  "kernelspec": {"display_name": "Python 3", "language": "python",
                                 "name": "python3"},
                  "language_info": {"name": "python", "version": "3"}},
              "nbformat": 4, "nbformat_minor": 5}
        return json.dumps(nb, indent=1, ensure_ascii=False) + "\n"

    def targets(self, root=ROOT):
        return {os.path.join(root, "code", self.stem + ".py"): self.script(),
                os.path.join(root, "notebooks", self.stem + ".ipynb"): self.notebook()}


def main(argv):
    check = "--check" in argv
    wanted, stale = set(), []
    for path in lesson_pages():
        for target, content in Lesson(path).targets().items():
            wanted.add(target)
            current = open(target, encoding="utf-8").read() if os.path.exists(target) else None
            if current == content:
                continue
            stale.append(os.path.relpath(target, ROOT))
            if not check:
                os.makedirs(os.path.dirname(target), exist_ok=True)
                with open(target, "w", encoding="utf-8") as f:
                    f.write(content)
    # generated files that no longer correspond to a lesson page
    orphans = [p for pattern in ("code/lesson-*.py", "notebooks/lesson-*.ipynb")
               for p in glob.glob(os.path.join(ROOT, pattern)) if p not in wanted]
    for p in orphans:
        stale.append(os.path.relpath(p, ROOT) + " (no such lesson)")
        if not check:
            os.remove(p)
    if check:
        for s in stale:
            print("stale:", s)
        print("generated files are up to date" if not stale else
              f"{len(stale)} generated file(s) out of date — run tools/sync_code.py")
        return 1 if stale else 0
    print(f"{len(wanted)} files in sync" + (f"; rewrote {len(stale)}" if stale else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
